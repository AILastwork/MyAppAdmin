class DocumentationPage(QWidget):
    def __init__(self, context: PageContext) -> None:
        super().__init__()
        self.context = context

        layout = QVBoxLayout(self)
        layout.setContentsMargins(18, 18, 18, 18)
        layout.setSpacing(12)
        layout.addWidget(page_title("Описание программы"))

        splitter = QSplitter()
        splitter.addWidget(self._build_sections_card())
        splitter.addWidget(self._build_text_card())
        splitter.setSizes([300, 980])
        layout.addWidget(splitter, 1)

        self.sections.setCurrentRow(0)

    def _build_sections_card(self) -> QWidget:
        card = Card("Разделы справки")
        self.sections = QListWidget()
        self.sections.setWordWrap(True)
        self.sections.setHorizontalScrollBarPolicy(Qt.ScrollBarAlwaysOff)
        self.sections.setSpacing(3)
        for index, (title, _) in enumerate(DOC_SECTIONS, start=1):
            self.sections.addItem(f"{index:02d}  {title}")
        self.sections.currentRowChanged.connect(self.show_section)
        card.layout.addWidget(self.sections)
        return card

    def _build_text_card(self) -> QWidget:
        card = Card(f"{APP_DISPLAY_NAME} {__version__}")
        self.text = QTextBrowser()
        self.text.setObjectName("DocumentationText")
        self.text.setOpenExternalLinks(False)
        card.layout.addWidget(self.text)
        return card

    def show_section(self, row: int) -> None:
        if row < 0 or row >= len(DOC_SECTIONS):
            return
        title, body = DOC_SECTIONS[row]
        lead = DOC_SECTION_LEADS.get(title, "")
        self.text.setHtml(
            f"""
            <html>
              <head><style>{DOC_STYLE}</style></head>
              <body>
                <div class="hero">
                  <div class="eyebrow">MYAPPADMIN · СПРАВКА</div>
                  <h1>{title}</h1>
                  <p class="lead">{lead}</p>
                </div>
                {body}
              </body>
            </html>
            """
        )
